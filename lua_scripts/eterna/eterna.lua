local BOSSES = {
    [910040] = { q = 915004, text = "Архив замолчал. Гайеф пал — но пепел ещё тёплый." },
    [910022] = { q = 915102, text = "Гуннар Тяжёлый пал. Северный лагерь остался без командира." },
    [910041] = { q = 915112, text = "Смотритель Архива мёртв. Ключ от последнего зала свободен." },
    [910043] = { q = 915124, text = "Магистр Душ повержен. Камни Джалады умолкли." },
}

for bossID, info in pairs(BOSSES) do
    RegisterCreatureEvent(bossID, 4, function(event, creature, killer)
        if not killer then return end
        local player = nil
        if killer:IsPlayer() then
            player = killer
        elseif killer:GetTypeId() == 4 then
            local owner = killer:GetOwner()
            if owner and owner:IsPlayer() then player = owner end
        end
        if player and player:HasQuest(info.q) then
            say(player, info.text)
        end
    end)
end

