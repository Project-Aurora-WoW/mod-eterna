SET NAMES utf8mb4;

-- ---------------------------------------------------------------------
--  1. FactionTemplate (серверный кэш клиентского FactionTemplate.dbc).
--     Копируем шаблон 35 (нейтральный), меняем только Faction.
--     Friend/Enemy группы остаются как у 35 — отношения не ломаются.
-- ---------------------------------------------------------------------
DELETE FROM `factiontemplate_dbc` WHERE `ID` = 5010;
INSERT INTO `factiontemplate_dbc`
(`ID`,`Faction`,`Flags`,`FactionGroup`,`FriendGroup`,`EnemyGroup`,
 `Enemies_1`,`Enemies_2`,`Enemies_3`,`Enemies_4`,
 `Friend_1`,`Friend_2`,`Friend_3`,`Friend_4`)
SELECT 5010, 5010, `Flags`, `FactionGroup`, `FriendGroup`, `EnemyGroup`,
       `Enemies_1`,`Enemies_2`,`Enemies_3`,`Enemies_4`,
       `Friend_1`,`Friend_2`,`Friend_3`,`Friend_4`
  FROM `factiontemplate_dbc` WHERE `ID` = 35;

-- ---------------------------------------------------------------------
--  2. Перевести дружелюбных NPC на 5010
--     (только те, кто должен числиться в Талиге)
-- ---------------------------------------------------------------------
UPDATE `creature_template` SET `faction` = 5010 WHERE `entry` IN (
  910000, -- Фернандо де Лакома
  910001, -- Ричард Окделл
  910002, -- Альдо Ракан
  910003, -- Камси
  910004, -- Элла
  910010, -- Стражник Талига
  910050, -- Справник лагеря
  910051, -- Леди Айрис
  910052, -- Магистр Ольгерд
  910053, -- Инквизитор Кай
  910054  -- Мать Кэртиана
);

-- ---------------------------------------------------------------------
--  3. Репутация за убийство Дриксена/Гайифы — в Талиг
-- ---------------------------------------------------------------------
DELETE FROM `creature_onkill_reputation` WHERE `creature_id` BETWEEN 910020 AND 910099;
INSERT INTO `creature_onkill_reputation`
(`creature_id`,`RewOnKillRepFaction1`,`RewOnKillRepFaction2`,`MaxStanding1`,`IsTeamAward1`,
 `RewOnKillRepValue1`,`MaxStanding2`,`IsTeamAward2`,`RewOnKillRepValue2`,`TeamDependent`)
VALUES
(910020, 5010, 0, 7, 0, 15, 0, 0, 0, 0),
(910021, 5010, 0, 7, 0, 50, 0, 0, 0, 0),
(910022, 5010, 0, 7, 0, 250, 0, 0, 0, 0),
(910023, 5010, 0, 7, 0, 10, 0, 0, 0, 0),
(910024, 5010, 0, 7, 0, 20, 0, 0, 0, 0),
(910030, 5010, 0, 7, 0, 25, 0, 0, 0, 0),
(910031, 5010, 0, 7, 0, 5, 0, 0, 0, 0),
(910040, 5010, 0, 7, 0, 500, 0, 0, 0, 0),
(910041, 5010, 0, 7, 0, 300, 0, 0, 0, 0),
(910042, 5010, 0, 7, 0, 15, 0, 0, 0, 0),
(910043, 5010, 0, 7, 0, 750, 0, 0, 0, 0);

-- ---------------------------------------------------------------------
--  4. Награды репутации за квесты — перевести с 72/29/935 на 5010
-- ---------------------------------------------------------------------
UPDATE `quest_template` SET
  `RewardFactionID1` = 5010, `RewardFactionValue1` = 3, `RewardFactionOverride1` = 0,
  `RewardFactionID2` = 0,     `RewardFactionValue2` = 0, `RewardFactionOverride2` = 0
 WHERE `ID` BETWEEN 915000 AND 915199 AND `RewardFactionID1` IN (72, 935);

