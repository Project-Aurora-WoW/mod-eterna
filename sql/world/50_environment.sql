--  Зоны мода на карте 0 (Драконий Погост, zone 139):
--    Лагерь Талига  — X -3840..-3810, Y -1270..-1235
--    Лагерь орлов   — X -4000..-3940, Y -1185..-1110   (книга 3)
--    Южные перевалы — X -3765..-3715, Y -1365..-1315   (книга 4)
--    Крепость       — X -3820..-3765, Y -1325..-1285   (книга 5)
--    Архив/Сердце   — X -3830..-3780, Y -1395..-1340   (книги 1,2,6)
--
--  Погода — game_weather (аккаунт-независимо, работает по zoneId).
--  Звук/вода/свет — поля areatable_dbc. На этой сборке areatable_dbc
--  почти пустая (только наша 5000), поэтому берём эталонные значения
--  из стандартного WotLK вместо копирования строки 139.
-- =====================================================================

SET NAMES utf8mb4;

-- ---------------------------------------------------------------------
--  1. ПОГОДА
--     Лагерь и Архив: мягкая — редкий дождь весной/осенью.
--     Орлы и перевалы: снежная — снег зимой, дождь летом.
--     Крепость: штормовая — грозы осенью.
--     Все значения — проценты (0..100), как в эталоне зоны 139.
-- ---------------------------------------------------------------------
DELETE FROM `game_weather` WHERE `zone` IN (5000, 5010, 5020, 5030);

INSERT INTO `game_weather`
(`zone`,`spring_rain_chance`,`spring_snow_chance`,`spring_storm_chance`,
 `summer_rain_chance`,`summer_snow_chance`,`summer_storm_chance`,
 `fall_rain_chance`,`fall_snow_chance`,`fall_storm_chance`,
 `winter_rain_chance`,`winter_snow_chance`,`winter_storm_chance`)
VALUES
-- 5000 Кэртиана / лагерь Талига — мягкий климат
(5000, 12, 0, 2, 14, 0, 3, 16, 0, 2, 8, 6, 1),
-- 5010 лагерь орлов — север, снег зимой
(5010, 10, 2, 3, 12, 0, 2, 14, 3, 3, 6, 25, 2),
-- 5020 южные перевалы — ветер и дождь
(5020, 15, 1, 4, 18, 0, 5, 20, 2, 4, 9, 12, 3),
-- 5030 крепость и стены — грозы
(5030, 13, 0, 6, 16, 0, 8, 18, 1, 7, 10, 8, 4);

-- ---------------------------------------------------------------------
--  2. ОКРУЖЕНИЕ ЗОНЫ 5000
--     Звук, вода, свет. Значения — из стандартных зон WotLK:
--       ZoneMusic 2201 — лесная тема Восточных королевств,
--       Ambience  8250 — ветер над лесом,
--       Liquid    2    — вода (пресная, уровня моря).
--     Если на сервере уже есть стандартная areatable_dbc, эти UPDATE
--     применятся к нашей записи и ничего не сломают.
-- ---------------------------------------------------------------------
UPDATE `areatable_dbc`
   SET `ZoneMusic`  = 2201,
       `AmbienceID` = 8250,
       `IntroSound` = 0,
       `SoundProviderPref` = 0,
       `LiquidTypeID_1` = 2,
       `LiquidTypeID_2` = 0,
       `LiquidTypeID_3` = 0,
       `LiquidTypeID_4` = 0,
       `MinElevation` = 100,
       `Ambient_Multiplier` = 1,
       `Flags` = 0
 WHERE `ID` = 5000;

