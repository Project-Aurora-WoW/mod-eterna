--    910091 Осадный маг Гайифы     mob_eterna_siege_mage
-- =====================================================================

SET NAMES utf8mb4;

-- 1. Снимаем имена C++-скриптов: кода для них нет, в логе были ошибки
UPDATE `creature_template`
   SET `ScriptName` = ''
 WHERE `entry` IN (910020, 910021, 910023, 910030, 910042,
                   910070, 910071, 910081, 910091);

-- 2. Включаем SmartAI
UPDATE `creature_template`
   SET `AIName` = 'SmartAI'
 WHERE `entry` IN (910020, 910021, 910023, 910030, 910042,
                   910070, 910071, 910081, 910091);

-- 3. Чистим возможные старые записи и создаём простые процедуры:
--    при входе в бой — боевой клич (эможут 15 = STATE, крик),
--    при смерти — эможут 36 (FLEE? нет — DEAD) чтобы завершить бой.
DELETE FROM `smart_scripts`
 WHERE `entryorguid` IN (910020, 910021, 910023, 910030, 910042,
                         910070, 910071, 910081, 910091)
   AND `source_type` = 0;

